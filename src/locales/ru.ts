/** Форма словаря: русский — эталон, остальные языки обязаны повторять его ключи. */
export type Dictionary = typeof ru;

type PluralExtra = `${string}_${"few" | "many"}`;

/**
 * Форма словаря других языков: те же ключи, но русские плюральные формы `_few`/`_many`
 * необязательны (в английском их нет, i18next берёт `_one`/`_other`).
 */
export type Translation = TranslationOf<Dictionary>;

type TranslationOf<T> = {
	[K in keyof T as K extends PluralExtra ? never : K]: T[K] extends string ? string : TranslationOf<T[K]>;
} & { [K in keyof T as K extends PluralExtra ? K : never]?: string };
